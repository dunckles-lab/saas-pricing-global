export function t(lang: LangCode, key: string, params: Record<string, string | number> = {}): string {
  const dictionary = UI_TRANSLATIONS[lang] || UI_TRANSLATIONS['en'];
  let text = dictionary[key] || UI_TRANSLATIONS['en'][key] || key;
  for (const [k, v] of Object.entries(params)) {
    text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  }
  return text;
}

export function getLocalizedPath(path: string, lang: LangCode): string {
  const cleanPath = path.startsWith('/') ? path : `/${path}`;
  if (lang === 'en') {
    return cleanPath;
  }
  return `/${lang}${cleanPath === '/' ? '' : cleanPath}`;
}
